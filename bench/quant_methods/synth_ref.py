# ------------------------------------------------------------------ case 1: traces
N_AX = 41
LOAD = [10, 13, 8]
PRED = np.array([1.0, 0.9, 0.75, 0.6, 0.5, 0.4, 0.3, 0.2], np.float32)
SHAPE = [100, 80, 45, 18, 5]
# candidate -> (apex sample offset of the scored apex in s, true peak centre sample, runs)
CANDS = {10: (40.4, 21, [0, 1, 2]), 20: (42.6, 20, [0, 1, 2]), 30: (37.0, 17, [0, 1, 2]),
         40: (4.0, 3, [0, 1]), 50: (40.0, 22, [0, 1, 2])}


def rt_axis():
    return np.array([100.0 + 2.0 * t for t in range(N_AX)], np.float32)


def pred_of(c):
    r = (c // 10) % 8
    return np.roll(PRED, r)


def observed(c, r, f):
    if c == 10 and f == 7:
        return False
    if c == 20 and f == 5 and r == 0:
        return False
    if c == 50 and f == 0:
        return False
    return True


def intensity(c, r, f):
    ax = np.zeros(N_AX, np.float64)
    centre = CANDS[c][1]
    p = int(round(float(pred_of(c)[f]) * 100))
    for t in range(N_AX):
        d = abs(t - centre)
        h = SHAPE[d] if d < len(SHAPE) else 0
        v = LOAD[r] * p * h
        v += ((r * 7 + f * 13 + t * 3 + c) % 11) * 10
        if c == 20 and f == 2 and r == 1 and centre + 1 <= t <= centre + 3:
            v += 50000
        if c == 30 and f == 0 and r == 2:
            v += 20000
        ax[t] = v
    return ax.astype(np.float32)


def nearest(axis, target):
    d = np.abs(axis.astype(np.float64) - target)
    return int(np.argmin(d))


def build_traces():
    K, W = 16, 33
    prec, frag, RT, I = [], [], [], []
    ax = rt_axis()
    pidx = 0
    for r in range(3):
        for c in sorted(CANDS):
            apex_rt, _, runs = CANDS[c]
            if r not in runs:
                continue
            apex = 100.0 + apex_rt
            k = nearest(ax, apex)
            pos = k - K + np.arange(W)
            ok = (pos >= 0) & (pos < N_AX)
            w = np.full(W, np.nan, np.float32)
            w[ok] = ax[pos[ok]]
            RT.append(w)
            prec.append(dict(pidx=pidx, run=r, candidate_id=c, condition="A", key=f"P{c}/2",
                             apex_idx=k, axis_len=N_AX, integration_apex_rt=apex))
            for f in range(8):
                obs = observed(c, r, f)
                tr = intensity(c, r, f)
                v = np.full(W, np.nan, np.float32)
                v[ok] = tr[pos[ok]] if obs else 0.0
                I.append(v)
                frag.append(dict(pidx=pidx, run=r, candidate_id=c, frag_name=f"f{f}",
                                 predicted_intensity=float(pred_of(c)[f]), observed=obs))
            pidx += 1
    meta = dict(dataset="synth", kind="hye2", K=K, W=W, runs=["r0", "r1", "r2"], conditions=["A"] * 3,
                padded=True)
    fr = pd.DataFrame(frag)
    fr["predicted_intensity"] = fr.predicted_intensity.astype(np.float32)
    return kit.Traces(meta, pd.DataFrame(prec), np.array(RT), fr, np.array(I))


def case1():
    T = build_traces()
    V = cpipe.recentre(T)
    out = {"shift": V.shift.tolist(), "rows": T.prec[["run", "candidate_id"]].values.tolist()}
    for rule in ("C2lf", "C3lf"):
        q = cpipe.RULES[rule](V)
        out[rule] = [None if not np.isfinite(x) else float(x) for x in q]
        out[f"phi_{rule}"] = cpipe.PHI_LOG[(V.name, rule)]
    out["d1_pred3"] = [None if not np.isfinite(x) else float(x) for x in kit.m_engine(V, selection="predicted")]
    out["d1_obs3"] = [None if not np.isfinite(x) else float(x) for x in kit.m_engine(V)]
    out["def_obs3"] = [None if not np.isfinite(x) else float(x) for x in kit.m_engine(T)]
    return out


# ------------------------------------------------------------------ case 2: stable set
class Lcg:
    def __init__(self, seed):
        self.s = seed

    def uniform(self):
        self.s = (self.s * 6364136223846793005 + 1442695040888963407) % (1 << 64)
        return (self.s >> 11) / float(1 << 53)

    def normal(self):
        acc = 0.0
        for _ in range(12):
            acc += self.uniform()
        return acc - 6.0


def stable_data(n_ions=4000, seed=17):
    g = Lcg(seed)
    off = [(0.3, 0.1), (0.0, 0.0), (-0.2, 0.2), (0.4, 0.4), (-0.3, -0.1), (0.1, -0.3)]
    rows = []
    for i in range(n_ions):
        m = i % 20
        sp = 0 if m <= 12 else (1 if m <= 16 else 2)
        ab = 15.0 + 6.0 * g.uniform()
        rt = 3000.0 * g.uniform()
        sd = 0.05 + 0.3 * (21.0 - ab) / 6.0
        for r, (a, b) in enumerate(off):
            in_a = r < 3
            fold = {(1, True): 0.5, (1, False): -0.5, (2, True): -1.0, (2, False): 1.0}.get((sp, in_a), 0.0)
            o = a + (b - a) * rt / 3000.0
            y = ab + fold + o + sd * g.normal()
            rr = rt + 2.0 * g.normal()
            miss = g.uniform() < 0.25 * (21.0 - ab) / 6.0
            if not miss:
                rows.append(dict(run=r, candidate_id=i, key=f"PEP{i}/2", y=y, rt=rr))
    return pd.DataFrame(rows)


def case2():
    d = stable_data().sort_values(["run", "candidate_id"], kind="mergesort").reset_index(drop=True)
    q = pd.DataFrame({"run": d.run.to_numpy(), "key": d.key.to_numpy(),
                      "quantity": np.exp2(d.y.to_numpy()), "rt": d.rt.to_numpy()})
    info_auto, info_k1 = [], []
    auto = G.norm_general(q, select="profile", est="median", frac=1.0, ref_mode="loo", n_bins=20,
                          min_per_bin=200, z=2.0, h_sd=1.0, iterations=3, info=info_auto)
    same = fnorm.profile(q)
    k1 = G.norm_general(q, select="profile", est="median", frac=1.0, ref_mode="loo", n_bins=20,
                        min_per_bin=200, z=2.0, h_sd=1.0, iterations=3, k=1, info=info_k1)
    info_k2 = []
    k2 = G.norm_general(q, select="profile", est="median", frac=1.0, ref_mode="loo", n_bins=20,
                        min_per_bin=200, z=2.0, h_sd=1.0, iterations=3, k=2, info=info_k2)
    assert np.array_equal(auto, same, equal_nan=True)
    pick = list(range(0, len(q), max(1, len(q) // 40)))
    return {"n_rows": int(len(q)), "pick": [[int(d.run[i]), int(d.candidate_id[i])] for i in pick],
            "log2_shift_auto": [float(np.log2(q.quantity.iloc[i] / auto[i])) for i in pick],
            "log2_shift_k1": [float(np.log2(q.quantity.iloc[i] / k1[i])) for i in pick],
            "log2_shift_k2": [float(np.log2(q.quantity.iloc[i] / k2[i])) for i in pick],
            "n_stable_k2": [x["n_stable"] for x in info_k2],
            "k_auto": [x["k"] for x in info_auto], "n_stable_auto": [x["n_stable"] for x in info_auto],
            "n_complete": [x["n_complete"] for x in info_auto], "lam": info_auto[-1]["lam"],
            "sigma": [x["sigma"] for x in info_auto]}


if __name__ == "__main__":
    print(json.dumps({"case1": case1(), "case2": case2()}, indent=1))
