"""Reference values of the quantification prototype on two small synthetic cases, for the
Rust unit tests of quant.window_centre = profile with fragment_selection = pattern_fit /
pattern_profile (`quant::pattern_tests`, case 1) and quant.normalisation = stable_set
(`quant_norm::tests::stable_set_reproduces_the_prototype`, case 2).

The data are generated by formulas that the Rust tests repeat exactly (integer intensities,
a 64-bit LCG). The prototype is the code of the 2026-10-26 quantification study (its kit,
`confirm/code/cpipe.py` and the family modules under `confirm/src`), which is not part of this
repository; point MUMDIA_QUANT_PROTOTYPE at its root.

usage: MUMDIA_QUANT_PROTOTYPE=<study root> python synth_ref.py   (prints JSON)
"""
